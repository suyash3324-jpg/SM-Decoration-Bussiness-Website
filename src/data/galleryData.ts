export interface Category {
  id: string;
  name: string;
  slug: string;
  description: string;
  icon: string;
  images: string[];
}

const encodeImagePath = (folder: string, filename: string): string => {
  return `/images/${encodeURIComponent(folder)}/${encodeURIComponent(filename)}`;
};

const buildCategory = (
  id: string,
  name: string,
  slug: string,
  description: string,
  icon: string,
  folder: string,
  filenames: string[]
): Category => ({
  id,
  name,
  slug,
  description,
  icon,
  images: filenames.map((f) => encodeImagePath(folder, f)),
});

